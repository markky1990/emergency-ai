// Records what each guide was checked against, with a fingerprint of the guide text.
//   node tools/stamp.js                      write verifications.js
//   node tools/stamp.js --restamp id1,id2    accept edited guides AFTER re-checking them
//
// Safety rule: if a guide's text changed since it was last stamped, this refuses to
// re-stamp it unless you name it with --restamp. That stops a quick edit from
// quietly keeping an old "verified" label.
const fs = require("fs");
const path = require("path");
const { cards, Trust, root } = require("./load");

const srcFile = path.join(root, "verifications-source.json");
const outFile = path.join(root, "verifications.js");
const source = JSON.parse(fs.readFileSync(srcFile, "utf8"));

const flag = process.argv.indexOf("--restamp");
const restampArg = flag > -1 ? (process.argv[flag + 1] || "") : "";
const restampAll = restampArg === "all"; // only after you have read every change and confirmed no fact changed
const restamp = new Set(restampArg.split(",").filter(Boolean));

const prev = Trust.VERIFICATIONS || {};
const out = {};
const changed = [], unknown = [];

for (const id of Object.keys(source)) {
  if (id.startsWith("_")) continue;
  const card = cards.find((c) => c.id === id);
  if (!card) { unknown.push(id); continue; }
  const entry = source[id];
  if (!entry.sources || !entry.sources.length) { console.log("No sources for " + id); process.exit(1); }
  const hash = Trust.hash(card);
  if (prev[id] && prev[id].hash !== hash && !restamp.has(id) && !restampAll) changed.push(id);
  out[id] = { date: entry.date, hash, sources: entry.sources };
  if (entry.note) out[id].note = entry.note;
}

if (unknown.length) { console.log("Unknown guide ids in verifications-source.json: " + unknown.join(", ")); process.exit(1); }
if (changed.length) {
  console.log("These guides changed since they were last checked:\n  " + changed.join("\n  "));
  console.log("\nRe-check them against their sources, then run:\n  node tools/stamp.js --restamp " + changed.join(","));
  process.exit(1);
}

const body = JSON.stringify(out, null, 2);
fs.writeFileSync(
  outFile,
  "// GENERATED by tools/stamp.js from verifications-source.json. Do not edit by hand.\n" +
    "(function (root) {\n  const V = " + body.replace(/^/gm, "  ").trimStart() + ";\n\n" +
    "  if (typeof module !== \"undefined\" && module.exports) module.exports = V;\n  else root.VERIFICATIONS = V;\n" +
    "})(typeof self !== \"undefined\" ? self : this);\n"
);
const missing = cards.filter((c) => !out[c.id]).map((c) => c.id);
console.log("Stamped " + Object.keys(out).length + " guides. Not yet checked (" + missing.length + "): " + missing.join(", "));
